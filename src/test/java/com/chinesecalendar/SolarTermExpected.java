    private static void add(int year, String... entries) {
        List<SolarTermDate> list = new ArrayList<>(entries.length);
        for (String entry : entries) {
            int split = entry.indexOf(':');
            LocalDate date = LocalDate.parse(entry.substring(0, split));
            SolarTerm term = SolarTerm.ofChinese(entry.substring(split + 1));
            list.add(new SolarTermDate(date, term));
        }
        BY_YEAR.put(year, list);
    }

